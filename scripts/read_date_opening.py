def seq(xs, ys, ds, start=0, shift=0):
    assert len(xs)==len(ys)==len(ds)
    out=[]
    for x,y,d in zip(xs,ys,ds):
        out.append((start,d,x,y if isinstance(y,list) else [y],shift));start+=d
    return out

